"""Turn a user's group and plugin assignments into what their sandbox starts with.

Three plugin kinds reach the sandbox as two files under /etc/dsh-cloud:

- bundle: an npm/git spec listed in policy.json. The image's provisioner
  installs and selects it once per user (`dsh plugin add`), so it behaves as a
  default the user may later remove; the install persists with the home.
- mcp: a `dsh-mcp-client` row inserted by admin.cordis.yml, the `--patch`
  overlay dsh applies after every user layer on each start. Its optional
  `install` npm spec is listed in policy.json and installed once per user
  before dsh starts, into the persisted ~/.local, so the command exists when
  dsh connects (running servers through `npx` races dsh's probe process).
- patch: raw Cordis patch rows appended to that same overlay.

Rows the overlay states win over the user's own patches; anything the user adds
in their profile is untouched and persists with their home.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any

import yaml

from .backends import SandboxResources
from .db import User

POLICY_PATH = "/etc/dsh-cloud/policy.json"
OVERLAY_PATH = "/etc/dsh-cloud/admin.cordis.yml"
PLUGIN_KEY = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
_SERVER_NAME = re.compile(r"^[A-Za-z0-9_-]{1,32}$")
_MCP_CLIENT = "@deepseek-ai/dsh-mcp-client"


@dataclass(frozen=True)
class SandboxPolicy:
    resources: SandboxResources
    idle_timeout_s: int
    max_lifetime_s: int
    files: dict[str, bytes]
    # The group's image reference; None runs the backend's default image.
    image: str | None = None


def build_policy(
    user: User, group: dict[str, Any], plugins: list[dict[str, Any]], image: str | None = None
) -> SandboxPolicy:
    bundles = [
        {"key": p["key"], "spec": p["config"]["spec"]} for p in plugins if p["kind"] == "bundle"
    ]
    npm = [
        {"key": p["key"], "spec": p["config"]["install"]}
        for p in plugins if p["kind"] == "mcp" and p["config"].get("install")
    ]
    return SandboxPolicy(
        resources=SandboxResources(mem_limit=group["mem_limit"], cpus=float(group["cpus"])),
        idle_timeout_s=int(group["idle_timeout_s"]),
        max_lifetime_s=int(group["max_lifetime_s"]),
        image=image,
        files={
            POLICY_PATH: (json.dumps({"user": user.username, "bundles": bundles, "npm": npm}, indent=2) + "\n").encode(),
            OVERLAY_PATH: render_overlay(plugins).encode(),
        },
    )


def render_overlay(plugins: list[dict[str, Any]]) -> str:
    """The admin overlay; JSON rows are valid YAML flow mappings, and raw patches append verbatim."""
    parts: list[str] = []
    for plugin in plugins:
        if plugin["kind"] == "mcp":
            row = {"id": f"dsh-cloud-mcp-{plugin['key']}", "name": _MCP_CLIENT, "config": mcp_row_config(plugin["config"])}
            parts.append(f"# {plugin['name']}\n- {json.dumps({'insert': [row]}, ensure_ascii=False)}\n")
        elif plugin["kind"] == "patch":
            parts.append(f"# {plugin['name']}\n{plugin['config']['yaml'].rstrip()}\n")
    if not parts:
        # dsh rejects an empty or comments-only patch file; [] is the empty layer.
        return "[]\n"
    return "# Generated by dsh-cloud gateway from the admin console; edits here are overwritten.\n" + "".join(parts)


def mcp_row_config(config: dict[str, Any]) -> dict[str, Any]:
    row: dict[str, Any] = {"serverName": config["serverName"], "transport": config["transport"]}
    if config["transport"] == "stdio":
        row["command"] = config["command"]
        for key in ("args", "env", "cwd"):
            if config.get(key):
                row[key] = config[key]
    else:
        row["url"] = config["url"]
        if config.get("headers"):
            row["headers"] = config["headers"]
    if config.get("toolCallTimeoutMs"):
        row["toolCallTimeoutMs"] = int(config["toolCallTimeoutMs"])
    return row


def validate_plugin(kind: str, key: str, config: dict[str, Any]) -> dict[str, Any]:
    """The normalized config, or ValueError naming the first invalid field."""
    if not PLUGIN_KEY.match(key):
        raise ValueError("标识只能包含小写字母、数字和连字符，且以字母或数字开头")
    if kind == "bundle":
        spec = str(config.get("spec", "")).strip()
        if not spec or any(c.isspace() for c in spec):
            raise ValueError("请填写插件包 spec，例如 @scope/name@1.2.3 或 git 地址")
        return {"spec": spec}
    if kind == "mcp":
        return _validate_mcp(config)
    if kind == "patch":
        text = str(config.get("yaml", ""))
        _parse_patch(text)
        return {"yaml": text}
    raise ValueError(f"未知的插件类型 {kind}")


def _validate_mcp(config: dict[str, Any]) -> dict[str, Any]:
    server = str(config.get("serverName", ""))
    if not _SERVER_NAME.match(server):
        raise ValueError("serverName 只能包含字母、数字、_ 和 -，最长 32 个字符")
    transport = config.get("transport")
    normalized: dict[str, Any] = {"serverName": server, "transport": transport}
    if transport == "stdio":
        command = str(config.get("command", "")).strip()
        if not command:
            raise ValueError("stdio 方式需要填写 command")
        args = config.get("args") or []
        if not isinstance(args, list) or not all(isinstance(a, str) for a in args):
            raise ValueError("args 必须是字符串列表")
        normalized.update(command=command, args=args, env=_string_map(config.get("env"), "env"))
        if config.get("cwd"):
            normalized["cwd"] = str(config["cwd"])
    elif transport == "streamable-http":
        url = str(config.get("url", "")).strip()
        if not url.startswith(("http://", "https://")):
            raise ValueError("streamable-http 方式需要 http(s) 地址")
        normalized.update(url=url, headers=_string_map(config.get("headers"), "headers"))
    else:
        raise ValueError("transport 只能是 stdio 或 streamable-http")
    if config.get("toolCallTimeoutMs"):
        normalized["toolCallTimeoutMs"] = int(config["toolCallTimeoutMs"])
    install = str(config.get("install") or "").strip()
    if install:
        if any(c.isspace() for c in install):
            raise ValueError("安装包只能填写一个 npm spec，例如 @scope/server@1.2.3")
        normalized["install"] = install
    return normalized


def _string_map(value: Any, name: str) -> dict[str, str]:
    if not value:
        return {}
    if not isinstance(value, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in value.items()):
        raise ValueError(f"{name} 必须是字符串到字符串的映射")
    return value


class _PatchLoader(yaml.SafeLoader):
    """Accepts dsh's `!!js` expressions so patches using them still validate."""


_PatchLoader.add_constructor("tag:yaml.org,2002:js", lambda loader, node: loader.construct_scalar(node))


def _parse_patch(text: str) -> None:
    try:
        rows = yaml.load(text, Loader=_PatchLoader)
    except yaml.YAMLError as err:
        raise ValueError(f"YAML 无法解析：{err}") from err
    if not isinstance(rows, list) or not rows or not all(isinstance(r, dict) for r in rows):
        raise ValueError("补丁必须是非空的 YAML 列表，每一项是一个映射（id 覆盖或 insert）")
    lines = [line for line in text.splitlines() if line.strip() and not line.lstrip().startswith("#")]
    if not lines[0].startswith("-"):
        raise ValueError("补丁请写成块格式列表（每行以 - 开头），以便和其他行拼接")
